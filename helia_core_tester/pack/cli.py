"""`helia_core_tester pack ...`: check a library's pack, and keep its generated descriptors in step."""

from __future__ import annotations

import os
from contextlib import contextmanager
from pathlib import Path, PurePosixPath
from typing import Any, Dict, Iterator, List, Mapping, Optional, Sequence, Tuple

import typer
import yaml

from helia_core_tester.contract.ir import ContractError
from helia_core_tester.core.config import configured_library
from helia_core_tester.core.discovery import find_repo_root_or_cwd
from helia_core_tester.core.errors import ConfigurationError
from helia_core_tester.core.library import LibraryProfile, require_supported, resolve_library
from helia_core_tester.pack import PackError

pack_app = typer.Typer(
    name="pack",
    help="Check a library's test pack: its modules, its descriptors and the descriptors its sources generate.",
    add_completion=False,
    no_args_is_help=True,
)

EXIT_DRIFT = 1
EXIT_UNAVAILABLE = 2

_LIBRARY_HELP = ("Directory with the library's hct-library.yaml (default: $HELIA_CORE_TESTER_LIBRARY, else library "
                 "in helia_core_tester.toml).")


def _fail(message: str, code: int) -> None:
    typer.echo(f"✗ {message}", err=True)
    raise typer.Exit(code=code)


def dump_documents(documents: Sequence[Mapping]) -> str:
    """The one serialisation of a descriptor file: documents in order, separated by ---."""
    return "---\n".join(yaml.safe_dump(dict(doc), sort_keys=False, default_flow_style=False, allow_unicode=True)
                        for doc in documents)


def _dump(docs: Any, where: str, rel: str) -> str:
    if not isinstance(docs, (list, tuple)) or not all(isinstance(doc, Mapping) for doc in docs):
        raise PackError(f"{where}: {rel} must map to a list of descriptor mappings, got {type(docs).__name__}")
    try:
        return dump_documents(docs)
    except yaml.YAMLError as exc:
        raise PackError(f"{where}: {rel} holds a value YAML cannot write ({exc}); give plain Python values") from None


def _relpath(value: object, where: str) -> str:
    if not isinstance(value, str):
        raise PackError(f"{where}: file name {value!r} is not a string")
    path = PurePosixPath(value)
    if "\\" in value or path.is_absolute() or ".." in path.parts or len(path.parts) != 2 or path.suffix != ".yaml":
        raise PackError(f"{where}: {value!r} must be <Family>/<stem>.yaml")
    return value


def generated_files(pack, contracts) -> Dict[str, str]:
    """What the pack's descriptor sources generate, by file; a source must be deterministic."""
    files: Dict[str, str] = {}
    for module, source in pack.registry.sources:
        where = f"{module}: descriptor_source"
        runs = []
        for _ in range(2):
            try:
                produced = source(contracts)
            except PackError:
                raise
            except Exception as exc:
                raise PackError(f"{where} failed: {type(exc).__name__}: {exc}") from exc
            if not isinstance(produced, Mapping):
                raise PackError(f"{where} returned {type(produced).__name__}, not a mapping of file to documents")
            runs.append({_relpath(rel, where): _dump(docs, where, rel) for rel, docs in produced.items()})
        if runs[0] != runs[1]:
            raise PackError(f"{where} gave different descriptors on two runs; a source must be deterministic")
        for rel, text in runs[0].items():
            if rel in files:
                raise PackError(f"{where}: {rel} is also generated by another source")
            files[rel] = text
    return files


def committed_files(directory: Path) -> Dict[str, str]:
    from helia_core_tester.pack.descriptors import descriptor_files

    files = {}
    for path in descriptor_files(directory):
        try:
            files[path.relative_to(directory).as_posix()] = path.read_text(encoding="utf-8")
        except UnicodeDecodeError as exc:
            raise PackError(f"{path}: not UTF-8 text: {exc.reason}") from None
        except OSError as exc:
            raise PackError(f"{path}: cannot read: {exc.strerror}") from None
    return files


def drift(expected: Mapping[str, str], committed: Mapping[str, str]) -> Tuple[List[str], List[str], List[str]]:
    missing = sorted(set(expected) - set(committed))
    extra = sorted(set(committed) - set(expected))
    changed = sorted(rel for rel in set(expected) & set(committed) if expected[rel] != committed[rel])
    return missing, extra, changed


@contextmanager
def _library_env(profile: LibraryProfile) -> Iterator[None]:
    from helia_core_tester.core.harness import PROFILE_ENV

    saved = {key: os.environ.get(key) for key in (PROFILE_ENV, "CMSIS_NN_ROOT")}
    if profile.profile_path is not None:
        os.environ[PROFILE_ENV] = str(profile.profile_path)
    os.environ["CMSIS_NN_ROOT"] = str(profile.source_root)
    try:
        yield
    finally:
        for key, value in saved.items():
            if value is None:
                os.environ.pop(key, None)
            else:
                os.environ[key] = value


def _profile(library: Optional[Path]) -> LibraryProfile:
    try:
        library_dir, _ = configured_library(find_repo_root_or_cwd(), library)
        if library_dir is None:
            _fail("no library: pass --library", EXIT_UNAVAILABLE)
        profile = require_supported(resolve_library(library_dir))
    except ConfigurationError as error:
        _fail(str(error), EXIT_UNAVAILABLE)
    if profile.pack is None:
        _fail(f"{profile.describe()}: its profile names no pack", EXIT_UNAVAILABLE)
    return profile


def _load(profile: LibraryProfile):
    from helia_core_tester.contract.render import load_current_contracts
    from helia_core_tester.core.harness import current_harness
    from helia_core_tester.pack.loader import pack_of

    pack = pack_of(profile)
    return pack, load_current_contracts(), [name for name, _ in current_harness().status.codes]


@pack_app.command()
def check(library: Optional[Path] = typer.Option(None, "--library", help=_LIBRARY_HELP)) -> None:
    """Load the pack, check every descriptor, and compare the generated ones with the committed ones."""
    from helia_core_tester.generation.io.descriptors import load_all_descriptors
    from helia_core_tester.pack.descriptors import load_case_descriptors

    profile = _profile(library)
    with _library_env(profile):
        try:
            pack, contracts, _ = _load(profile)
            expected = generated_files(pack, contracts) if pack.registry.sources else None
            committed = committed_files(pack.spec.descriptors)
            problems = None
            try:
                # The same loading generation does, so check and generate agree on every descriptor.
                cases, _ = load_case_descriptors(load_all_descriptors)
            except PackError as exc:
                problems, cases = str(exc), []
        except (ConfigurationError, ContractError, OSError) as exc:
            _fail(str(exc), EXIT_UNAVAILABLE)
    failed = False
    if expected is not None:
        missing, extra, changed = drift(expected, committed)
        for label, names in (("missing", missing), ("not generated", extra), ("changed", changed)):
            for name in names:
                typer.echo(f"✗ {name}: {label}", err=True)
        if missing or extra or changed:
            typer.echo(f"✗ the committed descriptors differ from what the pack generates; run "
                       f"`helia_core_tester pack sync --library {library or profile.source_root}`", err=True)
            failed = True
    else:
        typer.echo("• the pack registers no descriptor source, so there is nothing to compare; descriptors checked only")
    if problems:
        typer.echo(f"✗ {problems}", err=True)
        failed = True
    if failed:
        raise typer.Exit(code=EXIT_DRIFT)
    typer.echo(f"✓ {profile.library} pack: {len(cases)} case(s) in {len(committed)} file(s)")


@pack_app.command()
def sync(library: Optional[Path] = typer.Option(None, "--library", help=_LIBRARY_HELP)) -> None:
    """Rewrite the committed descriptors from the pack's sources, then check them."""
    profile = _profile(library)
    with _library_env(profile):
        try:
            pack, contracts, _ = _load(profile)
            if not pack.registry.sources:
                _fail("the pack registers no descriptor source; its descriptors are written by hand", EXIT_UNAVAILABLE)
            expected = generated_files(pack, contracts)
            directory = pack.spec.descriptors
            _, extra, _ = drift(expected, committed_files(directory))
            for rel in extra:
                (directory / rel).unlink()
            for rel, text in expected.items():
                target = directory / rel
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(text, encoding="utf-8")
        except (ConfigurationError, ContractError, OSError) as exc:
            _fail(str(exc), EXIT_UNAVAILABLE)
    typer.echo(f"✓ wrote {len(expected)} file(s), removed {len(extra)}")
    check(library)
