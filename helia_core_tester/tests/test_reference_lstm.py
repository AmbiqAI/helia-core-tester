@pytest.fixture(scope="module")
def lib():
    return get_bindings()


def _status(fn) -> str:
    with pytest.raises(ReferenceKernelError) as info:
        fn()
    return info.value.status


# --------------------------------------------------------- TFLM goldens

def _testdata_root() -> Path:
    root = os.environ.get("CMSIS_NN_ROOT")
    base = Path(root) if root else Path(__file__).resolve().parents[4]
    return base / "Tests" / "UnitTest" / "TestCases" / "TestData"


def _c_array(path: Path) -> np.ndarray:
    body = path.read_text().split("{", 1)[1].split("}", 1)[0]
    return np.array([int(v) for v in re.findall(r"-?\d+", body)], dtype=np.int64)


def _testdata(dataset: str):
    base = _testdata_root() / dataset
    if not (base / "config_data.h").exists():
        pytest.skip(f"ns-cmsis-nn UnitTest data {dataset} not available")
    macros = {}
    for line in (base / "config_data.h").read_text().splitlines():
        m = re.match(r"#define\s+(\w+)\s+(\S+)", line)
        if m:
            v = m.group(2)
            macros[m.group(1)[len(dataset) + 1:].lower()] = 1 if v == "true" else 0 if v == "false" else int(v)
    arrays = {p.stem: _c_array(p) for p in base.glob("*.h") if "{" in p.read_text()}
    return macros, arrays


@pytest.mark.parametrize("dataset,kind", [("lstm_1", "s8"), ("lstm_2", "s8"), ("lstm_1_s16", "s16"),
                                          ("lstm_2_s16", "s16"), ("lstm_one_time_step_s16", "s16")])
def test_integer_lstm_reproduces_tflm_goldens(lib, dataset, kind) -> None:
    p, a = _testdata(dataset)
    B, T, I, H, tm = p["batch_size"], p["time_steps"], p["input_size"], p["hidden_size"], p["time_major"]
    act = np.int16 if kind == "s16" else np.int8
    params = {"time_major": tm, "input_offset": p["input_zero_point"], "output_offset": p["output_zero_point"],
              "cell_clip": 0 if p["cell_clip"] >= 32767 else p["cell_clip"], "cell_scale_power": p["cell_scale_power"],
              "hidden_multiplier": p["output_multiplier"], "hidden_shift": p["output_shift"]}
    for key in ("forget_to_cell", "input_to_cell"):
        params[f"{key}_multiplier"], params[f"{key}_shift"] = p[f"{key}_multiplier"], p[f"{key}_shift"]
    for g in GATES:
        for src in ("input", "hidden"):
            params[f"{g}_{src}_multiplier"] = p[f"{g}_gate_{src}_multiplier"]
            params[f"{g}_{src}_shift"] = p[f"{g}_gate_{src}_shift"]
    shape = (T, B) if tm else (B, T)
    inputs = {
        "input": a["input_tensor"].astype(act).reshape(*shape, I),
        "input_weights": np.stack([a[f"{g}_gate_input_weights"].reshape(H, I) for g in GATES]).astype(np.int8),
        "recurrent_weights": np.stack([a[f"{g}_gate_hidden_weights"].reshape(H, H) for g in GATES]).astype(np.int8),
        "bias": np.stack([a[f"{g}_gate_bias"] for g in GATES]).astype(np.int64 if kind == "s16" else np.int32),
    }
    got = lib.run(f"lstm_{kind}", params, inputs, {"output": (*shape, H)})["output"]
    np.testing.assert_array_equal(got.reshape(-1), a["output"].astype(act))


# ------------------------------------------------- independent int model

def _sigmoid_table() -> list:
    src = (Path(__file__).resolve().parents[1] / "reference" / "src" / "activation" / "tanh_logistic.c").read_text()
    body = src[src.index("sigmoid_table[256] = {"):]
    return [int(v) for v in re.findall(r"\d+", body[body.index("{"):body.index("};")])]


TABLE = _sigmoid_table()


def lut16(x: int, mult: int, shift: int, is_tanh: bool) -> int:
    """reference_integer_ops::Logistic / Tanh, on Python ints."""
    v = (x * mult + ((1 << (shift - 1)) if shift else 0)) >> shift
    ax = abs(v)
    bits = 8 if is_tanh else 9
    uh = ax >> bits
    if is_tanh:
        r = (0xFFFF << 8) if uh >= 255 else (TABLE[uh] << 8) + (ax & 0xFF) * (TABLE[uh + 1] - TABLE[uh])
        r = r - (1 << 23) + (1 << 7) if v >= 0 else -r + (1 << 23) + (1 << 7) - 1
        return r >> 8
    r = (0x7FFF << 10) if uh >= 255 else (TABLE[uh] << 9) + (ax & 0x1FF) * (TABLE[uh + 1] - TABLE[uh])
    r = r + (1 << 9) if v >= 0 else (1 << 25) - r + (1 << 9) - 1
    return r >> 10


def mbqm64(x: int, m: int, shift: int) -> int:
    reduced = (m + (1 << 15)) >> 16 if m < 0x7FFF0000 else 0x7FFF
    total = 15 - shift
    return (x * reduced + (1 << (total - 1))) >> total


def sat16(v: int) -> int:
    return max(-32768, min(32767, v))


def lstm_model(kind, p, x, w, r, b):
    tm = p["time_major"]
    T, B = (x.shape[0], x.shape[1]) if tm else (x.shape[1], x.shape[0])
    H = w.shape[1]
    lo, hi = (-32768, 32767) if kind == "s16" else (-128, 127)
    req = (lambda a, m, s: mbqm64(a, m, s)) if kind == "s16" else mbqm
    power = p["cell_scale_power"]
    left = 15 + power - 3
    cm, cs = (3, -left) if left < 0 else (3 << left, 0)
    cell = [[0] * H for _ in range(B)]
    hid = [[p["output_offset"]] * H for _ in range(B)]
    out = np.zeros((T, B, H) if tm else (B, T, H), np.int64)
    for t in range(T):
        for bb in range(B):
            xv = [int(v) for v in (x[t, bb] if tm else x[bb, t])]
            gates = []
            for g, gate in enumerate(GATES):
                row = []
                for h in range(H):
                    acc = sum(int(w[g, h, k]) * (xv[k] + p["input_offset"]) for k in range(len(xv))) + int(b[g, h])
                    a1 = sat16(req(acc, p[f"{gate}_input_multiplier"], p[f"{gate}_input_shift"]))
                    acc2 = sum(int(r[g, h, k]) * (hid[bb][k] - p["output_offset"]) for k in range(H))
                    a2 = sat16(req(acc2, p[f"{gate}_hidden_multiplier"], p[f"{gate}_hidden_shift"]))
                    row.append(lut16(sat16(a1 + a2), 3, 0, g == 2))
                gates.append(row)
            for h in range(H):
                fc = sat16(mbqm(gates[0][h] * cell[bb][h], p["forget_to_cell_multiplier"], p["forget_to_cell_shift"]))
                ig = sat16(mbqm(gates[1][h] * gates[2][h], p["input_to_cell_multiplier"], p["input_to_cell_shift"]))
                cell[bb][h] = sat16(fc + ig)
                th = lut16(cell[bb][h], cm, cs, True)
                hv = max(lo, min(hi, mbqm(gates[3][h] * th, p["hidden_multiplier"], p["hidden_shift"]) + p["output_offset"]))
                hid[bb][h] = hv
                if tm:
                    out[t, bb, h] = hv
                else:
                    out[bb, t, h] = hv
    return out


@pytest.mark.parametrize("kind", ["s8", "s16"])
@pytest.mark.parametrize("time_major,batch,steps,power", [(0, 2, 4, -11), (1, 3, 3, -9), (0, 1, 5, -15)])
def test_integer_lstm_matches_a_python_model_of_lstm_eval(lib, kind, time_major, batch, steps, power) -> None:
    case = lstm_int_case(np.random.default_rng([batch, steps, len(kind)]), kind=kind, batch=batch, steps=steps,
                         input_size=5, hidden=4, time_major=bool(time_major), extras={}, cell_scale_power=power)
    got = lib.run(f"lstm_{kind}", case.params, case.inputs, {"output": case.output_shape})["output"]
    want = lstm_model(kind, case.params, case.inputs["input"], case.inputs["input_weights"],
                      case.inputs["recurrent_weights"], case.inputs["bias"])
    np.testing.assert_array_equal(got, want)
    assert len(np.unique(got)) > 3  # not saturated to a constant


def test_integer_lstm_cell_clip_bounds_the_cell(lib) -> None:
    case = lstm_int_case(np.random.default_rng(7), kind="s8", batch=1, steps=6, input_size=4, hidden=3,
                         time_major=False, extras={})
    free = lib.run("lstm_s8", case.params, case.inputs, {"output": case.output_shape})["output"]
    clipped = lib.run("lstm_s8", dict(case.params, cell_clip=64), case.inputs, {"output": case.output_shape})["output"]
    want = lstm_model("s8", dict(case.params, cell_clip=0), case.inputs["input"], case.inputs["input_weights"],
                      case.inputs["recurrent_weights"], case.inputs["bias"])
    np.testing.assert_array_equal(free, want)
    assert not np.array_equal(free, clipped)


def test_integer_lstm_rejects_invalid_params_and_shapes(lib) -> None:
    case = lstm_int_case(np.random.default_rng(8), kind="s8", batch=1, steps=2, input_size=3, hidden=2,
                         time_major=False, extras={})
    run = lambda params=case.params, inputs=case.inputs, out=case.output_shape: lib.run(
        "lstm_s8", params, inputs, {"output": out})
    run()
    assert _status(lambda: run(dict(case.params, time_major=2))) == "E_PARAM"
    assert _status(lambda: run(dict(case.params, cell_scale_power=1))) == "E_PARAM"
    assert _status(lambda: run(dict(case.params, forget_input_shift=31))) == "E_PARAM"
    assert _status(lambda: run(dict(case.params, input_input_multiplier=-1))) == "E_PARAM"
    assert _status(lambda: run(dict(case.params, output_offset=128))) == "E_PARAM"
    assert _status(lambda: run(dict(case.params, cell_clip=-1))) == "E_PARAM"
    assert _status(lambda: run(out=(1, 2, 3))) == "E_SHAPE"
    bad = dict(case.inputs, input_weights=np.ascontiguousarray(case.inputs["input_weights"][:3]))
    assert _status(lambda: run(inputs=bad)) == "E_SHAPE"
    bad = dict(case.inputs, bias=np.ascontiguousarray(case.inputs["bias"][:, :1]))
    assert _status(lambda: run(inputs=bad)) == "E_SHAPE"


def test_case_builder_derives_tflm_quantization_and_honours_zero_points() -> None:
    case = lstm_int_case(np.random.default_rng(9), kind="s16", batch=1, steps=2, input_size=3, hidden=2,
                         time_major=False, extras={"input_zero_point": 7, "output_zero_point": -5}, cell_scale_power=-10)
    p, ctx = case.params, case.context
    assert p["input_offset"] == -7 and ctx["input_zero_point"] == -7 and p["output_offset"] == -5
    assert (p["forget_to_cell_multiplier"], p["forget_to_cell_shift"]) == quantize_multiplier(2.0 ** -15)
    assert (p["input_to_cell_multiplier"], p["input_to_cell_shift"]) == quantize_multiplier(2.0 ** -20)
    assert (p["hidden_multiplier"], p["hidden_shift"]) == quantize_multiplier(2.0 ** -30 / ctx["scales"]["hidden"])
    assert case.inputs["bias"].dtype == np.int64 and np.any(case.inputs["bias"] != 0)
    with pytest.raises(ValueError, match="outside"):
        lstm_int_case(np.random.default_rng(1), kind="s8", batch=1, steps=1, input_size=1, hidden=1,
                      time_major=False, extras={"input_zero_point": 200})
    with pytest.raises(ValueError, match="cell_scale_power"):
        lstm_int_case(np.random.default_rng(1), kind="s8", batch=1, steps=1, input_size=1, hidden=1,
                      time_major=False, extras={}, cell_scale_power=3)
    with pytest.raises(ValueError, match="positive"):
        lstm_int_case(np.random.default_rng(1), kind="s8", batch=1, steps=0, input_size=1, hidden=1,
                      time_major=False, extras={})


# --------------------------------------------------------------- float

def lstm_float_model(x, w, r, b, time_major, clip):
    x, w, r = x.astype(np.float64), w.astype(np.float64), r.astype(np.float64)
    b = np.zeros(w.shape[:2]) if b.size == 0 else b.astype(np.float64)
    seq = x if time_major else x.transpose(1, 0, 2)
    T, B, _ = seq.shape
    H = w.shape[1]
    h, c = np.zeros((B, H)), np.zeros((B, H))
    sig = lambda v: 1.0 / (1.0 + np.exp(-v))
    out = np.zeros((T, B, H))
    for t in range(T):
        pre = [seq[t] @ w[g].T + h @ r[g].T + b[g] for g in range(4)]
        f, i, g, o = sig(pre[0]), sig(pre[1]), np.tanh(pre[2]), sig(pre[3])
        c = f * c + i * g
        if clip > 0:
            c = np.clip(c, -clip, clip)
        h = o * np.tanh(c)
        out[t] = h
    return out if time_major else out.transpose(1, 0, 2)


@pytest.mark.parametrize("dtype,entry,tol", [(np.float32, "lstm_f32", 2e-6), (np.float16, "lstm_f16", 2e-2)])
@pytest.mark.parametrize("time_major,clip,bias", [(0, 0.0, True), (1, 0.5, True), (0, 0.0, False)])
def test_float_lstm_follows_the_float64_model(lib, dtype, entry, tol, time_major, clip, bias) -> None:
    rng = np.random.default_rng([time_major, int(bias)])
    B, T, I, H = 2, 5, 3, 4
    x = rng.uniform(-1, 1, (T, B, I) if time_major else (B, T, I)).astype(dtype)
    w = rng.uniform(-0.5, 0.5, (4, H, I)).astype(dtype)
    r = rng.uniform(-0.5, 0.5, (4, H, H)).astype(dtype)
    b = rng.uniform(-0.25, 0.25, (4, H)).astype(dtype) if bias else np.zeros((0,), dtype)
    got = lib.run(entry, {"time_major": time_major, "cell_clip": clip},
                  {"input": x, "input_weights": w, "recurrent_weights": r, "bias": b}, {"output": (*x.shape[:2], H)})
    np.testing.assert_allclose(got["output"].astype(np.float64), lstm_float_model(x, w, r, b, time_major, clip),
                               atol=tol, rtol=tol)
    if clip:
        assert np.all(np.abs(got["output"]) <= 1.0)


def test_float_lstm_rejects_a_bad_clip_and_shapes(lib) -> None:
    x = np.zeros((1, 2, 3), np.float32)
    w = np.zeros((4, 2, 3), np.float32)
    r = np.zeros((4, 2, 2), np.float32)
    b = np.zeros((0,), np.float32)
    run = lambda clip=0.0, rr=r: lib.run("lstm_f32", {"time_major": 0, "cell_clip": clip},
                                         {"input": x, "input_weights": w, "recurrent_weights": rr, "bias": b},
                                         {"output": (1, 2, 2)})
    run()
    assert _status(lambda: run(-1.0)) == "E_PARAM"
    assert _status(lambda: run(math.inf)) == "E_PARAM"
    assert _status(lambda: run(rr=np.zeros((4, 2, 3), np.float32))) == "E_SHAPE"
